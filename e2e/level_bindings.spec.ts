import { expect, test } from "@playwright/test";
import { entry, hostCall, surfaceCallArg, waitForSurface } from "./lib";

test("GM wall scope authoring audits bindings, blocks stale edits, undoes and persists", async ({ page }) => {
  test.setTimeout(90_000);
  await page.goto(entry + "?e2e=1"); await waitForSurface(page, "app");
  await page.locator('[data-canvas-layer="gm"]').click(); await page.locator('[data-canvas-tool="wall"]').click();
  const a = await surfaceCallArg<{ x: number; y: number }>(page, "app", "screenOf", { x: 500, y: 400 });
  const b = await surfaceCallArg<{ x: number; y: number }>(page, "app", "screenOf", { x: 800, y: 400 });
  await page.mouse.move(a.x, a.y); await page.mouse.down(); await page.mouse.move(b.x, b.y, { steps: 6 }); await page.mouse.up();
  await expect.poll(async () => (await hostCall<unknown[]>(page, "walls")).length).toBe(1);
  const before = await hostCall<{ id: string; c: number[] }[]>(page, "walls");
  const wall = before[0]; if (!wall) throw new Error("wall missing");
  await page.locator('[data-tab="scenes"]').click();
  const editor = page.locator('[data-level-drafts]').first(); await editor.locator(":scope > summary").click();
  await editor.getByRole("button", { name: "Add draft level", exact: true }).click();
  await editor.getByRole("button", { name: "Apply draft levels", exact: true }).click();
  await expect(editor.getByRole("status")).toContainText("Draft saved");
  const level = await editor.locator("[data-level-id]").first().getAttribute("data-level-id");
  if (!level) throw new Error("level missing");
  const bindings = editor.locator("[data-level-bindings]"); await bindings.locator(":scope > summary").click();
  await expect(bindings).toContainText("do not hide other floors");
  await bindings.getByLabel("Membership object type", { exact: true }).selectOption("walls");
  await bindings.getByLabel("Membership object", { exact: true }).selectOption(wall.id);
  await bindings.getByLabel("Wall level scope", { exact: true }).selectOption("levels");
  const apply = bindings.getByRole("button", { name: "Apply assignment", exact: true });
  await expect(apply).toBeDisabled(); await bindings.getByRole("checkbox", { name: "Base", exact: true }).check();
  await apply.click(); await expect(bindings.getByRole("status")).toContainText("Assignment saved");
  const audit = bindings.locator(`[data-level-binding-audit="${level}"]`);
  await expect(audit).toContainText("0 tokens · 1 walls");
  expect(await hostCall(page, "walls")).toEqual(before); // geometry/axes readback unchanged
  await page.locator("#gm-undo").click(); await expect(audit).toContainText("0 tokens · 0 walls");
  await expect(apply).toBeDisabled(); await expect(bindings.getByRole("alert")).toContainText("changed");
  await bindings.getByRole("button", { name: "Reload assignment", exact: true }).click();
  await expect(bindings.getByLabel("Wall level scope", { exact: true })).toHaveValue("legacy");
  await page.locator("#gm-redo").click(); await expect(audit).toContainText("0 tokens · 1 walls");
  await bindings.getByRole("button", { name: "Reload assignment", exact: true }).click();
  await expect(bindings.getByLabel("Wall level scope", { exact: true })).toHaveValue("levels");
  await editor.getByRole("button", { name: "Remove draft level", exact: true }).click();
  await expect(editor.getByRole("button", { name: "Apply draft levels", exact: true })).toBeDisabled();
  await expect(apply).toBeDisabled();
  await editor.getByRole("button", { name: "Reload draft", exact: true }).click();
  await page.getByRole("button", { name: "Close world", exact: true }).click();
  await page.getByRole("button", { name: /^Open$/, exact: false }).first().click(); await waitForSurface(page, "app");
  await page.locator('[data-tab="scenes"]').click(); await editor.locator(":scope > summary").click(); await bindings.locator(":scope > summary").click();
  await expect(audit).toContainText("0 tokens · 1 walls");
  await bindings.getByLabel("Membership object type", { exact: true }).selectOption("walls");
  await bindings.getByLabel("Membership object", { exact: true }).selectOption(wall.id);
  await bindings.getByLabel("Wall level scope", { exact: true }).selectOption("legacy"); await apply.click();
  await expect(audit).toContainText("0 tokens · 0 walls");
  expect(await hostCall(page, "walls")).toEqual(before);
});

test("GM explicitly assigns token feet, clears membership without moving, and undoes", async ({ page }) => {
  await page.goto(entry + "?e2e=1"); await waitForSurface(page, "app");
  await page.getByRole("button", { name: "Add token", exact: true }).click();
  await expect.poll(() => hostCall<number>(page, "tokenCount")).toBe(1);
  await page.locator('[data-tab="scenes"]').click();
  const editor = page.locator('[data-level-drafts]').first(); await editor.locator(":scope > summary").click();
  await editor.getByRole("button", { name: "Add draft level", exact: true }).click();
  const row = editor.locator("[data-level-id]").first();
  await row.getByLabel("top", { exact: true }).fill("20");
  await row.getByLabel("bottom", { exact: true }).fill("10");
  await row.getByLabel("floorZ", { exact: true }).fill("10");
  await editor.getByRole("button", { name: "Apply draft levels", exact: true }).click();
  await expect(editor.getByRole("status")).toContainText("Draft saved");
  const id = await row.getAttribute("data-level-id"); if (!id) throw new Error("level missing");
  const bindings = editor.locator("[data-level-bindings]"); await bindings.locator(":scope > summary").click();
  await bindings.getByLabel("Membership object", { exact: true }).selectOption({ index: 1 });
  await bindings.getByLabel("Token destination level", { exact: true }).selectOption(id);
  await expect(bindings).toContainText("Apply moves feet to Z 10");
  const apply = bindings.getByRole("button", { name: "Apply assignment", exact: true }); await apply.click();
  await expect(bindings.getByRole("status")).toContainText("Assignment saved");
  await expect(bindings).toContainText("Current feet Z: 10");
  const audit = bindings.locator("[data-level-binding-audit]"); await expect(audit).toContainText("1 tokens · 0 walls");
  await bindings.getByLabel("Token destination level", { exact: true }).selectOption(""); await apply.click();
  await expect(audit).toContainText("0 tokens · 0 walls"); await expect(bindings).toContainText("Current feet Z: 10");
  await page.locator("#gm-undo").click(); await expect(audit).toContainText("1 tokens · 0 walls");
  await page.locator("#gm-undo").click(); await expect(bindings).toContainText("Current feet Z: 0");
  await expect(audit).toContainText("0 tokens · 0 walls");
});
